"""Bump every shipped version marker to a new value.

Usage: python scripts/bump_version.py 2.60.0 [--dry-run]

The script only rewrites literal occurrences of the old version string in
known tracked files. It never touches .venv, build, dist, installer-output,
or .bak/.log backup files. source-manifest.json is regenerated by
scripts/package_source.py after the bump, so it is intentionally skipped.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Files that are known to embed the release version.
TARGETS = (
    "desktop/app.py",
    "desktop/agent_cb.js",
    "desktop/bridge.py",
    "desktop/config.py",
    "desktop/internal_browser.py",
    "desktop/__init__.py",
    "desktop/ui/index.html",
    "desktop/ui/app.js",
    "desktop/ui/i18n.js",
    "desktop/translations/en.json",
    "desktop/translations/fa.json",
    "ChatBridge.iss",
    "ChatBridge.spec",
    "ChatBridge.bat",
    "build_exe.bat",
    "build_installer.bat",
    "shared/protocol.json",
    "pyproject.toml",
    "README.md",
    "README.html",
    "README.fa.md",
    "CHANGELOG.md",
    "worklog.md",
    "scripts/ver_check.py",
    "scripts/package_source.py",
    "scripts/render_readme.py",
    "scripts/ui_dom_check.py",
    "scripts/visual_check_agent.py",
    "scripts/visual_check_ui.py",
    "docs/api-contract.md",
    "docs/INSTALL.md",
    "docs/original-spec.md",
    "docs/validation.md",
    "tests/test_agent_rules.py",
    "tests/test_app_integration.py",
    "tests/test_bridge.py",
)
# Anything before the first digit ensures we replace a full dotted version.
OLD_VERSION_RE = re.compile(r"(?<![\d.])2\.50\.0(?![\d.])")


def bump(old: str, new: str, dry_run: bool) -> int:
    pattern = re.compile(re.escape(old).join((r"(?<![\d.])", r"(?![\d.])")))
    changed = 0
    for name in TARGETS:
        path = ROOT / name
        if not path.is_file():
            print(f"skip (missing): {name}")
            continue
        text = path.read_text(encoding="utf-8")
        if not pattern.search(text):
            continue
        updated = pattern.sub(new, text)
        if dry_run:
            print(f"would update: {name}")
        else:
            path.write_text(updated, encoding="utf-8")
            print(f"updated: {name}")
        changed += 1
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("new", help="new version, e.g. 2.60.0")
    parser.add_argument("--old", default="2.50.0", help="old version, default 2.50.0")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    if not re.fullmatch(r"\d+\.\d+\.\d+", args.new):
        print("new version must look like X.Y.Z", file=sys.stderr)
        return 2
    changed = bump(args.old, args.new, args.dry_run)
    print(f"{'planned' if args.dry_run else 'changed'}: {changed} file(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
